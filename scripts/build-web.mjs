function pageDocument(meta, jbc) {
  const data = [
    `data-target="#mount"`,
    `data-policy="${meta.policy}"`,
    `data-fault="${meta.fault}"`,
    `data-isolation="${meta.isolation}"`,
    `data-app="${meta.name}"`,
    (meta.capabilities ?? []).length ? `data-capabilities="${meta.capabilities.join(" ")}"` : "",
  ].filter(Boolean).join(" ");
  return `<!doctype html>
<!-- GENERATED by scripts/build-web.mjs — 源文件 web/apps/${meta.name}.jlc，改源码后跑 npm run build:web -->
<html lang="zh-CN">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<meta name="referrer" content="no-referrer">
<title>JLC 0.3 · ${meta.title}</title>
<link rel="stylesheet" href="../playground.css">
</head>
<body class="app-page" data-app="${meta.name}">
<header class="app-bar">
  <a class="app-back" href="../index.html">← 控制台</a>
  <span class="app-title">${meta.title}</span>
  <span class="app-meta" data-role="meta">装载中…</span>
  <span class="app-spacer"></span>
  <button type="button" data-role="reload" title="按当前参数重新装载">重新装载</button>
  <button type="button" data-role="probe" title="在沙箱内部试探宿主资源">隔离自检</button>
</header>
<p class="app-summary">${meta.summary}</p>
<main id="mount" class="app-mount"></main>
<section class="app-audit" data-role="audit" hidden>
  <h2>被策略收回的接口</h2>
  <ul data-role="denied-list"></ul>
</section>
<footer class="app-foot">
  <p class="app-demo">${meta.demo}</p>
  <p class="muted">本页零网络依赖：字节码内联在下面的 <code>script[type="text/jbc"]</code> 里，运行时是 <code>../jlc-runtime.js</code>（不含编译器）。查询串 <code>?policy=&amp;fault=&amp;isolation=</code> 可覆盖策略。</p>
</footer>
<script id="jlc-module" type="text/jbc" ${data}>
${base64(jbc)}
</script>
<script src="../jlc-runtime.js"></script>
<script src="../app-page.js"></script>
</body>
</html>
`;
}

/* ------------------------------------------------------------------ */
/* 主流程                                                             */
/* ------------------------------------------------------------------ */

function main() {
  const runtimeSource = readFileSync(join(ROOT, "jlc-vm.js"), "utf8");
  const compilerSource = readFileSync(join(ROOT, "jlc-compiler.js"), "utf8");
  const facadeSource = readFileSync(join(ROOT, "jlc.js"), "utf8");

  const runtimeExports = [
    "VERSION", "ABI_VERSION", "BYTECODE_VERSION",
    "createVMKernel", "VMKernel", "JLCVM", "JLCProgram",
    "loadModule", "encodeModule", "decodeModule", "verifyModule", "auditModule", "disassembleModule",
    "resolvePolicy", "checkPermissions", "policyViolation", "scopeStylesheet",
    "SECURITY_PROFILES", "SYSCALLS",
    "HARD_BLOCKED_TAGS", "HARD_BLOCKED_PROPERTIES", "BLOCKED_TAGS", "URL_ATTRIBUTES",
    "JLCRuntimeError", "JLCVerifyError", "JLCPolicyError", "JLCQuotaError", "JLCIsolationError",
  ];
  emit(
    join(WEB, "jlc-runtime.js"),
    bundle(
      [{ name: "jlc-vm.js", source: runtimeSource }],
      `global.JLCRuntime = Object.freeze({\n${runtimeExports.map((name) => `  ${name},`).join("\n")}\n});`,
      `JLC 运行时（仅 VM，无编译器）· v${VERSION} · abi ${ABI_VERSION} · bytecode ${BYTECODE_VERSION}`,
    ),
  );

  const fullExports = [
    ...runtimeExports.filter((name) => !["JLCVM", "VMKernel"].includes(name)),
    "JLCCompileError", "tokenize", "Parser", "optimizeProgram", "compileAst", "CompilerKernel",
    "JLCKernel", "createKernel", "JLC",
  ];
  emit(
    join(WEB, "jlc-full.js"),
    bundle(
      [
        { name: "jlc-vm.js", source: runtimeSource },
        { name: "jlc-compiler.js", source: compilerSource },
        { name: "jlc.js", source: facadeSource },
      ],
      `global.JLCFull = Object.freeze({\n${fullExports.map((name) => `  ${name},`).join("\n")}\n});`,
      `JLC 全量门面（编译器 + VM）· v${VERSION}`,
    ),
  );

  const apps = readdirSync(APPS)
    .filter((file) => file.endsWith(".jlc"))
    .sort()
    .map((file) => file.slice(0, -4));
  const registry = [];

  for (const name of apps) {
    const source = readFileSync(join(APPS, `${name}.jlc`), "utf8");
    const meta = readMeta(source, name);
    if (!PROFILES.includes(meta.policy)) throw new Error(`${name}: 未知策略档 ${meta.policy}`);
    let built;
    try {
      built = buildApp(source, name, meta.policy);
    } catch (error) {
      throw new Error(`${name}: 按 ${meta.policy} 档预检失败\n${error.message}`);
    }
    const { module, requirements, bytes, denialsByProfile, sites } = built;
    emit(join(APPS, `${name}.html`), pageDocument(meta, bytes));
    registry.push({
      name,
      title: meta.title,
      summary: meta.summary,
      demo: meta.demo,
      policy: meta.policy,
      fault: meta.fault,
      isolation: meta.isolation,
      capabilities: meta.capabilities,
      href: `./apps/${name}.html`,
      source: `./apps/${name}.jlc`,
      bytes: bytes.length,
      hash: sha256(source),
      app: module.app,
      functions: module.functions.length,
      pool: module.pool.length,
      sites,
      requirements: requirements.map((item) => ({
        kind: item.kind,
        detail: item.detail,
        key: `${item.kind}:${item.detail}`,
        sites: (item.sites ?? []).slice(0, 3),
      })),
      denialsByProfile,
    });
  }

  const registryText = `/* GENERATED by scripts/build-web.mjs — 不要手改 */\n/* JLC 游乐场注册表 · v${VERSION} · ${registry.length} 个应用 */\n(function (global) {\n"use strict";\nglobal.JLC_REGISTRY = Object.freeze(${JSON.stringify({
    version: VERSION,
    abi: ABI_VERSION,
    bytecode: BYTECODE_VERSION,
    profiles: PROFILES.map((name) => ({ name, policy: publicPolicy(resolvePolicy(name)) })),
    apps: registry,
  }, null, 2)});\n})(typeof globalThis !== "undefined" ? globalThis : this);\n`;
  emit(join(WEB, "registry.js"), registryText);

  console.log(`${CHECK ? "漂移" : "生成"} ${out.length} 个文件${out.length ? `:\n  ${out.join("\n  ")}` : ""}`);
  if (CHECK && out.length) {
    console.error("产物与源码不同步：请运行 npm run build:web");
    process.exitCode = 1;
  }
}

function publicPolicy(policy) {
  const keep = [
    "profile", "label", "fingerprint", "urlSchemes", "allowDataUrls", "allowBlobUrls", "allowCustomElements", "allowEventAttributes",
    "allowSandboxedFrames", "allowHtmlInjection", "allowNetwork", "allowWindowEvents", "strictUrls",
    "frameSandbox", "frameMinIntervalMs", "htmlMaxChars", "maxDomNodes", "maxStyleBytes", "styleScoping",
  ];
  const result = {};
  for (const key of keep) {
    const value = policy[key];
    if (typeof value === "object" && value !== null && "size" in value) result[key] = [...value];
    else if (value !== undefined) result[key] = value;
  }
  return result;
}

main();
