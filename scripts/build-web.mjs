/*
 * 游乐场构建脚本：web/apps/*.jlc → 自包含沙箱页 + 注册表 + 浏览器可用的经典脚本运行时。
 * Copyright (c) 2026 JLC contributors. MIT licensed.
 *
 *   node scripts/build-web.mjs          生成 web/ 下的产物
 *   node scripts/build-web.mjs --check  只比对，有漂移就退出码 1（npm run check 用）
 *
 * 产物：
 *   web/jlc-runtime.js  仅运行时（无编译器），app 页面用它装载 .jbc
 *   web/jlc-full.js     运行时 + 编译器 + 门面，控制台页面用它现场编译
 *   web/apps/<名>.html   自包含沙箱页（内联 base64 .jbc，零网络请求，可 file:// 直开）
 *   web/registry.js     元数据 + 接口清单 + 各策略档的拒绝预告（全局脚本，同样避开 CORS）
 *
 * 设计约束：游乐场必须能在 GitHub Pages（静态托管）与 file:// 下工作，
 * 因此不使用 ES module import（opaque origin 下会被 CORS 拦），改成拼接成经典脚本。
 */

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  ABI_VERSION,
  BYTECODE_VERSION,
  VERSION,
  checkPermissions,
  encodeModule,
  loadModule,
  resolvePolicy,
} from "../jlc-vm.js";
import { compileAst } from "../jlc-compiler.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const WEB = join(ROOT, "web");
const APPS = join(WEB, "apps");
const PROFILES = ["strict", "open", "trusted"];
const CHECK = process.argv.includes("--check");

/* ------------------------------------------------------------------ */
/* 工具                                                               */
/* ------------------------------------------------------------------ */

const out = [];
function emit(absolute, text) {
  const name = relative(ROOT, absolute);
  const previous = (() => {
    try {
      return readFileSync(absolute, "utf8");
    } catch {
      return null;
    }
  })();
  if (previous === text) return;
  if (CHECK) {
    out.push(name);
    return;
  }
  mkdirSync(dirname(absolute), { recursive: true });
  writeFileSync(absolute, text);
  out.push(name);
}

/** 把 ES module 源码剥成可在 IIFE 里跑的经典脚本源码。 */
function deModule(source, name) {
  if (/<\/script/i.test(source)) throw new Error(`${name}: 源码里出现 </script，无法内联到 HTML`);
  if (/\bimport\.meta\b/.test(source)) throw new Error(`${name}: 使用了 import.meta，无法拼成经典脚本`);
  if (/^\s*(?:for\s+)?await\b/m.test(source)) throw new Error(`${name}: 顶层 await 无法拼成经典脚本`);
  return source
    .replace(/^\uFEFF/, "")
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*["'][^"']+["'];?[ \t]*$/gm, "")
    .replace(/^import\s*["'][^"']+["'];?[ \t]*$/gm, "")
    .replace(/^export\s+default\s+[A-Za-z_$][\w$]*;?[ \t]*$/gm, "")
    .replace(/^export\s*\{[^}]*\}\s*(?:from\s*["'][^"']+["'])?\s*;?[ \t]*$/gm, "")
    .replace(/^export\s+(?=(?:const|let|var|async\s+function|function|class)\b)/gm, "");
}

function topLevelNames(source) {
  const found = new Set();
  const pattern = /^(?:const|let|var)\s+([A-Za-z_$][\w$]*)|^(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)|^class\s+([A-Za-z_$][\w$]*)/gm;
  for (const match of source.matchAll(pattern)) found.add(match[1] ?? match[2] ?? match[3]);
  return found;
}

function bundle(parts, tail, banner) {
  const stripped = parts.map((part) => deModule(part.source, part.name));
  const seen = new Map();
  stripped.forEach((source, index) => {
    for (const name of topLevelNames(source)) {
      if (seen.has(name)) {
        throw new Error(`拼接冲突：${name} 同时出现在 ${parts[seen.get(name)].name} 与 ${parts[index].name} 的顶层`);
      }
      seen.set(name, index);
    }
  });
  return `/* GENERATED by scripts/build-web.mjs — 不要手改，改源码后跑 npm run build:web */\n/* ${banner} */\n(function (global) {\n"use strict";\n\n${stripped.join("\n\n")}\n\n${tail}\n})(typeof globalThis !== "undefined" ? globalThis : this);\n`;
}

function base64(bytes) {
  return Buffer.from(bytes).toString("base64");
}

function sha256(text) {
  return createHash("sha256").update(text).digest("hex").slice(0, 16);
}

/* ------------------------------------------------------------------ */
/* 应用页元数据                                                        */
/* ------------------------------------------------------------------ */

function readMeta(source, name) {
  const block = /^\/\*\*?\s*@jlc-page([\s\S]*?)\*\//.exec(source);
  const meta = { name, title: name, summary: "", policy: "open", isolation: "soft", fault: "degrade", capabilities: [], demo: "" };
  if (!block) return meta;
  for (const line of block[1].split("\n")) {
    const match = /^\s*\*\s*([A-Za-z-]+)\s*:([^*]*)$/.exec(line);
    if (!match) continue;
    const key = match[1].trim();
    const value = match[2].trim();
    if (key === "capabilities") meta.capabilities = value ? value.split(/[,\s]+/).filter(Boolean) : [];
    else if (key in meta) meta[key] = value;
  }
  return meta;
}

/** 编译期检查：声明档下必须挂得住（manifest 模式给出聚合预检清单）。 */
function buildApp(source, name, policy) {
  const { module } = compileAst(source, { sourceName: `web/apps/${name}.jlc`, policy, policyMode: "manifest" });
  const bytes = encodeModule(module);
  const reload = loadModule(bytes, { sourceName: `${name}.jbc` });
  const requirements = module.requirements ?? [];
  const sites = requirements.reduce((total, item) => total + (item.sites?.length ?? 0), 0);
  if ((reload.requirements ?? []).length !== requirements.length) throw new Error(`${name}: .jbc 往返后接口清单不一致`);
  const denialsByProfile = {};
  for (const profile of PROFILES) {
    const resolved = resolvePolicy(profile);
    denialsByProfile[profile] = checkPermissions(requirements, resolved).map((denied) => ({
      key: denied.key,
      kind: denied.kind,
      detail: denied.detail,
      reason: denied.reason,
      sites: (denied.sites ?? []).slice(0, 3),
    }));
  }
  return {
    module,
    requirements,
    reload,
    bytes,
    denialsByProfile,
  };
}

/* ------------------------------------------------------------------ */
/* 页面模板                                                           */
